"""生成 Go 用的 GBK 双字节映射表（仅生成，不参与运行时）。

GBK 双字节区：首字节 0x81-0xFE，尾字节 0x40-0xFE（0x7F 空）。
表大小 126 * 190 = 23940，值 0 表示该码位无映射（或需要 4 字节 GB18030 扩展）。
"""
import codecs
import os

LEADS = range(0x81, 0xFF)
TRAILS = [c for c in range(0x40, 0xFF) if c != 0x7F]

rows = []
mapped = 0
for lead in LEADS:
    for trail in TRAILS:
        raw = bytes([lead, trail])
        try:
            ch = raw.decode("gbk")
        except UnicodeDecodeError:
            rows.append(0)
            continue
        cp = ord(ch)
        if cp > 0xFFFF:
            rows.append(0)
            continue
        rows.append(cp)
        mapped += 1

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine", "parse", "gbk_table.go")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Code generated by scripts/gen_gbk.py; DO NOT EDIT.\n\n")
    f.write("package parse\n\n")
    f.write("// gbkTrail 尾字节顺序：0x40-0x7E -> 0..62，0x80-0xFE -> 63..189。\n")
    f.write("var gbkTable = [23940]uint16{\n")
    for i in range(0, len(rows), 12):
        chunk = rows[i:i + 12]
        f.write("\t" + ", ".join(str(v) for v in chunk) + ",\n")
    f.write("}\n")

print(f"wrote {out}: {len(rows)} entries, {mapped} mapped")
